CREATE DATABASE IF NOT EXISTS triad CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE triad;

CREATE TABLE Paciente (
 idPaciente INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL, telefone VARCHAR(30) NOT NULL UNIQUE,
 dataNasc DATE NULL, genero VARCHAR(40) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE, senha VARCHAR(255) NOT NULL
);
CREATE TABLE Profissional (
 idProfissional INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL, telefone VARCHAR(30) NOT NULL UNIQUE,
 dataNasc DATE NULL, genero VARCHAR(40) NOT NULL,
 documentoCip VARCHAR(80) NOT NULL UNIQUE, email VARCHAR(150) NOT NULL UNIQUE,
 senha VARCHAR(255) NOT NULL
);
CREATE TABLE Diario (
 idDiario INT AUTO_INCREMENT PRIMARY KEY,
 idPaciente INT NOT NULL, texto TEXT NOT NULL, data DATE NOT NULL,
 enviado BOOLEAN NOT NULL DEFAULT FALSE, resposta TEXT NULL,
 idProfissionalResposta INT NULL, dataResposta DATETIME NULL,
 CONSTRAINT fk_diario_paciente FOREIGN KEY(idPaciente) REFERENCES Paciente(idPaciente) ON DELETE CASCADE,
 CONSTRAINT fk_diario_profissional FOREIGN KEY(idProfissionalResposta) REFERENCES Profissional(idProfissional) ON DELETE SET NULL
);
CREATE TABLE Tecnica (
 idTecnica INT AUTO_INCREMENT PRIMARY KEY, tipo VARCHAR(100) NOT NULL, descricao TEXT NOT NULL
);
CREATE TABLE PacienteTecnica (
 idPacienteTecnica INT AUTO_INCREMENT PRIMARY KEY,
 idPaciente INT NOT NULL, idTecnica INT NOT NULL, dataUtilizacao DATETIME DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(idPaciente) REFERENCES Paciente(idPaciente) ON DELETE CASCADE,
 FOREIGN KEY(idTecnica) REFERENCES Tecnica(idTecnica) ON DELETE CASCADE
);
CREATE TABLE Evento (
 idEvento INT AUTO_INCREMENT PRIMARY KEY, tema VARCHAR(180) NOT NULL, data DATE NOT NULL, descricao TEXT NULL
);
CREATE TABLE Livro (
 idLivro INT AUTO_INCREMENT PRIMARY KEY, titulo VARCHAR(180) NOT NULL,
 mes VARCHAR(20) NOT NULL, ano INT NOT NULL, autor VARCHAR(120) NOT NULL
);
CREATE TABLE FraseDiaria (
 idFrase INT AUTO_INCREMENT PRIMARY KEY, data DATE NOT NULL UNIQUE, frase VARCHAR(500) NOT NULL
);
